def print_triangular_numbers(x):     # This is the function.
    for z in range(1, x + 1):
        print(z, "\t", z * (z + 1) / 2) # This \t function really comes in handy!

print_triangular_numbers(5)     # This gives the first five triangular numbers.
        
    
    


    
    

